function TimeBucket([int]$h) {
    if ($h -le 5) { '1.새벽(0~5시)' } elseif ($h -le 11) { '2.오전(6~11시)' } elseif ($h -le 17) { '3.오후(12~17시)' } else { '4.밤(18~23시)' }
}

function DayType([string]$date, [string]$dow) {
    if ($Holidays[$date]) { '공휴일' } elseif ($dow -eq '토' -or $dow -eq '일') { '주말' } else { '평일' }
}

function Split-CsvLine([string]$line) {
    # 원본 파일은 모든 값이 "..." 로 감싸져 있고 값 안에 쉼표가 없음
    $line.Trim().Trim('"') -split '","'
}
